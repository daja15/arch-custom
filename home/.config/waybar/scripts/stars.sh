#!/bin/sh
# ╭──────────────────────────────────────────────────────────────╮
# │  Іконка зірок на екрані (waybar). Клік → desk.sh toggle stars,│
# │  той шле сигнал RTMIN+14 — без опитування.                   │
# ╰──────────────────────────────────────────────────────────────╯
if pgrep -x stars >/dev/null; then
    printf '{"text":"\\udb81\\udcce","tooltip":"Зірки на екрані увімкнено — клік, щоб вимкнути","class":"on"}\n'
else
    printf '{"text":"\\udb81\\udcd2","tooltip":"Зірки на екрані вимкнено — клік, щоб увімкнути","class":"off"}\n'
fi
